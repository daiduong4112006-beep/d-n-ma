/** Tiêu đề trang hiển thị trên thanh bên theo mục đang mở */
export const getPageTitle = (activeTab: string): string =>
    activeTab === 'admin' ? 'Quản lý người dùng' : activeTab === 'dashboard' || activeTab === 'my-quizzes'
      ? 'Bộ đề của tôi'
      : activeTab === 'quiz-detail'
      ? 'Chi tiết bộ đề & Ôn tập'
      : activeTab === 'create-quiz'
      ? 'Tạo bộ đề mới'
      : activeTab === 'edit-quiz'
      ? 'Chỉnh sửa câu hỏi'
      : activeTab === 'quiz-mode'
      ? 'Thi trắc nghiệm'
      : activeTab === 'quiz-result'
      ? 'Kết quả bài thi'
      : activeTab === 'review-mode'
      ? 'Xem lại đáp án'
      : activeTab === 'practice-mistakes'
      ? 'Luyện câu hay sai'
      : activeTab === 'statistics'
      ? 'Thống kê kết quả'
      : activeTab === 'import-export'
      ? 'Nhập & Xuất đề thi'
      : activeTab === 'saved-vocabulary'
      ? 'Từ cần lưu ý ghi nhớ'
      : activeTab === 'japanese'
      ? 'Môn học'
      : 'Cài đặt hệ thống';
